// Command gen writes the Go types of the Codex app-server protocol the adapter uses and the schema part the
// fake app-server of the tests checks requests against, from the schema the installed codex generates.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"slices"
	"sort"
	"strings"
	"unicode"
)

// roots are the types the adapter sends or reads.
var roots = []string{
	"InitializeParams", "InitializeResponse", "GetAccountParams", "GetAccountResponse", "ConfigReadParams",
	"SkillsListParams", "SkillsListResponse", "SkillsExtraRootsSetParams",
	"ThreadStartParams", "ThreadStartResponse", "ThreadResumeParams", "ThreadResumeResponse",
	"TurnStartParams", "TurnStartResponse", "TurnInterruptParams", "TurnSteerParams",
	"TurnCompletedNotification", "ItemStartedNotification", "ItemCompletedNotification", "ErrorNotification",
	"ThreadTokenUsageUpdatedNotification", "AccountRateLimitsUpdatedNotification",
	"CommandExecutionRequestApprovalParams", "CommandExecutionRequestApprovalResponse",
	"FileChangeRequestApprovalParams", "FileChangeRequestApprovalResponse",
	"McpServerElicitationRequestResponse", "PermissionsRequestApprovalResponse",
}

// methods are the unions whose methods and parameter types the fake knows.
var methods = []string{"ClientRequest", "ClientNotification", "ServerRequest", "ServerNotification"}

var ref = regexp.MustCompile(`#/definitions/(?:v2/)?([A-Za-z0-9_]+)`)

type def = map[string]any

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: gen <protocol.go> <protocol.schema.json>")
		os.Exit(2)
	}
	dir, err := os.MkdirTemp("", "codex-schema-")
	if err != nil {
		fail(err)
	}
	defer os.RemoveAll(dir)
	if out, err := exec.Command("codex", "app-server", "generate-json-schema", "--experimental", "--out", dir).CombinedOutput(); err != nil {
		fail(fmt.Errorf("codex app-server generate-json-schema: %v: %s", err, out))
	}
	defs := load(dir)
	keep := map[string]def{}
	todo := slices.Clone(roots)
	for len(todo) > 0 {
		name := todo[0]
		todo = todo[1:]
		if _, done := keep[name]; done {
			continue
		}
		d, ok := defs[name]
		if !ok {
			fail(fmt.Errorf("no type %s in the schema", name))
		}
		keep[name] = d
		b, _ := json.Marshal(d)
		for _, m := range ref.FindAllStringSubmatch(string(b), -1) {
			todo = append(todo, m[1])
		}
	}
	names := map[string]map[string]string{}
	for _, u := range methods {
		names[u] = map[string]string{}
		for _, v := range defs[u]["oneOf"].([]any) {
			props := v.(def)["properties"].(def)
			e, _ := props["method"].(def)["enum"].([]any)
			params := ""
			if p, ok := props["params"].(def); ok {
				if r, ok := p["$ref"].(string); ok {
					params = strings.TrimPrefix(r, "#/definitions/")
				}
			}
			for _, m := range e {
				names[u][m.(string)] = params
			}
		}
	}
	out, err := json.MarshalIndent(map[string]any{"methods": names, "definitions": keep}, "", " ")
	if err != nil {
		fail(err)
	}
	if err := os.WriteFile(os.Args[2], append(out, '\n'), 0o644); err != nil {
		fail(err)
	}
	g := &gen{defs: keep, done: map[string]bool{}}
	for _, r := range roots {
		g.named(r)
	}
	src, err := format.Source(g.source())
	if err != nil {
		fail(err)
	}
	if err := os.WriteFile(os.Args[1], src, 0o644); err != nil {
		fail(err)
	}
}

// load reads the schema bundle; its v2 types sit under definitions.v2.
func load(dir string) map[string]def {
	b, err := os.ReadFile(filepath.Join(dir, "codex_app_server_protocol.schemas.json"))
	if err != nil {
		fail(err)
	}
	b = []byte(ref.ReplaceAllString(string(b), "#/definitions/$1"))
	var bundle struct {
		Definitions map[string]json.RawMessage `json:"definitions"`
	}
	if err := json.Unmarshal(b, &bundle); err != nil {
		fail(err)
	}
	defs := map[string]def{}
	var v2 map[string]def
	if err := json.Unmarshal(bundle.Definitions["v2"], &v2); err != nil {
		fail(err)
	}
	for name, d := range v2 {
		defs[name] = d
	}
	for name, raw := range bundle.Definitions {
		if name == "v2" {
			continue
		}
		var d def
		if err := json.Unmarshal(raw, &d); err != nil {
			fail(err)
		}
		defs[name] = d
	}
	return defs
}

type gen struct {
	defs  map[string]def
	done  map[string]bool
	decls map[string]string
}

func (g *gen) source() []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/provider/codex/gen from the Codex app-server schema. DO NOT EDIT.\n\npackage codex\n\nimport \"encoding/json\"\n\n")
	keys := make([]string, 0, len(g.decls))
	for k := range g.decls {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		b.WriteString(g.decls[k] + "\n")
	}
	b.WriteString("var _ json.RawMessage\n")
	return b.Bytes()
}

func (g *gen) emit(name, decl string) {
	if g.decls == nil {
		g.decls = map[string]string{}
	}
	g.decls[name] = decl
}

// named declares the type of a definition and gives its Go name.
func (g *gen) named(name string) string {
	goName := exported(name)
	if g.done[name] {
		return goName
	}
	g.done[name] = true
	d := g.defs[name]
	g.emit(goName, g.decl(goName, d))
	return goName
}

// kind tells how a definition is spelled in Go: a struct, a string, or raw JSON.
func (g *gen) kind(name string) string {
	d := g.defs[name]
	switch {
	case d["properties"] != nil:
		return "struct"
	case d["enum"] != nil || d["type"] == "string":
		return "string"
	}
	return "raw"
}

func (g *gen) decl(goName string, d def) string {
	if props, ok := d["properties"].(def); ok {
		return "type " + goName + " " + g.structOf(goName, props, required(d))
	}
	if d["enum"] != nil || d["type"] == "string" {
		return "type " + goName + " string\n"
	}
	for _, key := range []string{"oneOf", "anyOf"} {
		if vs, ok := d[key].([]any); ok {
			for _, v := range vs {
				vd := v.(def)
				if title, ok := vd["title"].(string); ok && vd["properties"] != nil {
					vn := exported(title)
					if !g.done["#"+vn] {
						g.done["#"+vn] = true
						g.emit(vn, "type "+vn+" "+g.structOf(vn, vd["properties"].(def), required(vd)))
					}
				}
			}
		}
	}
	return "type " + goName + " = json.RawMessage\n"
}

func (g *gen) structOf(owner string, props def, req []string) string {
	keys := make([]string, 0, len(props))
	for k := range props {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var b strings.Builder
	b.WriteString("struct {\n")
	for _, k := range keys {
		must := slices.Contains(req, k)
		pd, _ := props[k].(def)
		t := g.field(owner+exported(k), pd, must)
		tag := k
		if !must {
			tag += ",omitempty"
		}
		fmt.Fprintf(&b, "\t%s %s `json:%q`\n", exported(k), t, tag)
	}
	b.WriteString("}\n")
	return b.String()
}

// field spells a property type; optional structs are pointers, unions and untyped values raw JSON.
func (g *gen) field(scope string, p def, must bool) string {
	if r, ok := p["$ref"].(string); ok {
		name := strings.TrimPrefix(r, "#/definitions/")
		t := g.named(name)
		if g.kind(name) == "struct" && !must {
			return "*" + t
		}
		return t
	}
	for _, key := range []string{"anyOf", "oneOf"} {
		if vs, ok := p[key].([]any); ok {
			var rest []def
			for _, v := range vs {
				if v.(def)["type"] != "null" {
					rest = append(rest, v.(def))
				}
			}
			if len(rest) == 1 {
				return g.field(scope, rest[0], false)
			}
			return "json.RawMessage"
		}
	}
	if all, ok := p["allOf"].([]any); ok && len(all) == 1 {
		return g.field(scope, all[0].(def), must)
	}
	t := p["type"]
	if ts, ok := t.([]any); ok {
		for _, x := range ts {
			if x != "null" {
				t = x
			}
		}
	}
	switch t {
	case "string":
		return "string"
	case "integer":
		return "int64"
	case "number":
		return "float64"
	case "boolean":
		return "bool"
	case "array":
		if items, ok := p["items"].(def); ok {
			return "[]" + g.field(scope+"Item", items, true)
		}
		return "[]json.RawMessage"
	case "object":
		if props, ok := p["properties"].(def); ok {
			if !g.done["#"+scope] {
				g.done["#"+scope] = true
				g.emit(scope, "type "+scope+" "+g.structOf(scope, props, required(p)))
			}
			if must {
				return scope
			}
			return "*" + scope
		}
		return "map[string]any"
	}
	return "json.RawMessage"
}

func required(d def) []string {
	var out []string
	if rs, ok := d["required"].([]any); ok {
		for _, r := range rs {
			out = append(out, r.(string))
		}
	}
	return out
}

// exported turns a JSON name into a Go identifier.
func exported(s string) string {
	var b strings.Builder
	up := true
	for _, r := range s {
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) {
			up = true
			continue
		}
		if up {
			r = unicode.ToUpper(r)
			up = false
		}
		b.WriteRune(r)
	}
	out := b.String()
	for _, w := range []string{"Id", "Url", "Json", "Mcp", "Http", "Api"} {
		out = replaceWord(out, w, strings.ToUpper(w))
	}
	return out
}

// replaceWord upper-cases an initialism where it ends a word, so ThreadId becomes ThreadID but Identity stays.
func replaceWord(s, w, to string) string {
	var b strings.Builder
	for i := 0; i < len(s); {
		if strings.HasPrefix(s[i:], w) {
			end := i + len(w)
			if end == len(s) || unicode.IsUpper(rune(s[end])) || unicode.IsDigit(rune(s[end])) {
				b.WriteString(to)
				i = end
				continue
			}
		}
		b.WriteByte(s[i])
		i++
	}
	return b.String()
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}
